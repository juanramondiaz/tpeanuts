"""Turn the YAML specification of a benchmark into an HTCondor submit file (``.sub``) for Artemisa.

The YAML files in ``benchmarks/suites/`` are the single description of a benchmark; the submit files are generated from
them and are not versioned (``benchmarks/condor/generated/``). A generated file starts with a comment that names its
YAML and the ``spec_hash``, and ``--check`` finds the ones that no longer match.

    python benchmarks/condor/render.py benchmarks/suites/1_intrinsic/tpeanuts_cpu_float64.yaml
    python benchmarks/condor/render.py --all                    # every specification, and the order to submit them in
    python benchmarks/condor/render.py --all --chain            # also submit_all.sh: submit, wait, check, next
    python benchmarks/condor/render.py --check                  # exit 1 if a generated file is stale or an orphan

Run it from the repository root (the submit files use paths relative to it, as the ``.sub`` is submitted from there; the
CSV path is relative too, so the file is valid on the cluster whatever the checkout path is there).

DAGMan is not available on the cluster, so the order of ``condor.after`` is carried out by ``submit_all.sh``: it submits
one job, waits for it with ``condor_wait`` and goes on only if the expected output exists, so two measurements never
share a machine and a failed job stops the sequence. An output that was already there is moved to ``<file>.previous``
first, so a failure cannot be mistaken for success and nothing is lost. Specifications marked ``optional`` are left
out of the chain unless ``--include-optional`` is given.

Module contents:
    GENERATED
        Default directory of the generated files.
    RenderError
        A specification that cannot be rendered.
    expected_output(...)
        The file a job must leave, relative to the repository root.
    render(...)
        The text of the submit file of one specification.
    launch_order(...)
        The specifications in an order that respects ``condor.after``.
    render_chain(...)
        The text of ``submit_all.sh``.
    main(...)
        Command-line entry point.
"""

from __future__ import annotations

import argparse
import os
import shlex
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence

REPOSITORY = Path(__file__).resolve().parents[2]
if str(REPOSITORY) not in sys.path:  # run as a script from anywhere: ``python benchmarks/condor/render.py``
    sys.path.insert(0, str(REPOSITORY))

from benchmarks.common.spec import Spec, SpecError, discover, load_spec  # noqa: E402

GENERATED = Path(__file__).resolve().parent / "generated"
LOGS = "benchmarks/condor/logs"
RUN_SH = "benchmarks/condor/run.sh"
EXPORT_OUTPUT = "benchmarks/results/reference_tpeanuts.npz"
_BANNER = "Generated by benchmarks/condor/render.py"


class RenderError(ValueError):
    """A specification that cannot be rendered into a submit file."""


def _relative(path: Path) -> str:
    """``path`` relative to the repository root, with forward slashes; an error if it lies outside it."""
    try:
        return Path(path).resolve().relative_to(REPOSITORY).as_posix()
    except ValueError as error:
        raise RenderError(
            f"{path} is outside the repository: the submit file must use paths relative to its root"
        ) from error


def job_name(spec: Spec, smoke: bool = False) -> str:
    """``<series>_<name>``, unique across the series (a name alone may repeat); ``_smoke`` for a quick run."""
    return f"{spec.series}_{spec.name}{'_smoke' if smoke else ''}"


def sub_path(spec: Spec, directory: Path = GENERATED, smoke: bool = False) -> Path:
    """Where the submit file of ``spec`` is written."""
    return Path(directory) / f"{job_name(spec, smoke)}.sub"


def expected_output(spec: Spec, smoke: bool = False) -> str:
    """The file a finished job must leave, relative to the repository root (the CSV, or the reference ``.npz``)."""
    if spec.backend == "export":
        return EXPORT_OUTPUT
    return _relative(spec.output_csv(smoke))


def _arguments(spec: Spec, smoke: bool) -> str:
    argv = spec.to_argv(smoke=smoke)
    if spec.backend != "export":  # to_argv writes the absolute path of the CSV; the job needs the relative one
        argv[argv.index("--output") + 1] = expected_output(spec, smoke)
    for arg in argv:
        if not arg or any(ch in arg for ch in " \t\"'\\"):
            raise RenderError(f"{spec.id}: the argument {arg!r} would need quoting in a submit file")
    return " ".join(argv)


def render(spec: Spec, *, smoke: bool = False) -> str:
    """The text of the submit file of one specification.

    Args:
        spec: The specification.
        smoke: Render the quick-run variant (``--smoke``, its own CSV and job name).

    Returns:
        The file content, ending in a newline; the same input always gives the same text.

    Raises:
        RenderError: If the CSV is outside the repository or an argument would need quoting.
    """
    name = job_name(spec, smoke)
    yaml = _relative(spec.path) if spec.path is not None else f"{spec.id}.yaml"
    lines = [
        f"# {_BANNER} from {yaml} (spec_hash {spec.spec_hash(smoke)}). Do not edit: edit the YAML and render again.",
        f"# {spec.description}" if spec.description else None,
        f"# Submit from the repository root:  condor_submit {_relative(sub_path(spec, smoke=smoke))}",
        f"# Leaves: {expected_output(spec, smoke)}",
        f"# Run after: {', '.join(spec.condor.after)} (wait until each has finished)" if spec.condor.after else None,
        "# The resources of a job are part of what is measured: change them in the YAML, not here.",
        "universe                = vanilla",
        f"executable              = {RUN_SH}",
        "getenv                  = False",
        "should_transfer_files   = NO",
        "# ^ Artemisa shares the filesystem with the worker nodes, so nothing is transferred.",
        f"output                  = {LOGS}/$(JobName).$(ClusterId).out",
        f"error                   = {LOGS}/$(JobName).$(ClusterId).err",
        f"log                     = {LOGS}/$(JobName).$(ClusterId).log",
        f"JobName                 = {name}",
        f"request_cpus            = {spec.condor.request_cpus}",
        f"request_memory          = {spec.condor.request_memory}",
        f"request_gpus            = {spec.condor.request_gpus}" if spec.condor.request_gpus else None,
    ]
    env = spec.env_vars()
    if env:
        lines.append('environment             = "' + " ".join(f"{k}={v}" for k, v in sorted(env.items())) + '"')
    lines += [f"arguments               = {_arguments(spec, smoke)}", "queue"]
    return "\n".join(line for line in lines if line is not None) + "\n"


def launch_order(specs: Sequence[Spec]) -> List[Spec]:
    """The specifications ordered so that each comes after those it names in ``condor.after``.

    Dependencies that are not among ``specs`` are assumed to have run already. The order among independent ones is
    alphabetical, so it is the same every time.

    Args:
        specs: The selected specifications.

    Returns:
        The ordered list.

    Raises:
        RenderError: If the dependencies contain a cycle.
    """
    by_id = {s.id: s for s in specs}
    waiting = {s.id: {d for d in s.condor.after if d in by_id} for s in specs}
    ordered: List[Spec] = []
    while waiting:
        ready = sorted(i for i, deps in waiting.items() if not deps)
        if not ready:
            raise RenderError("condor.after has a cycle among " + ", ".join(sorted(waiting)))
        for i in ready:
            ordered.append(by_id[i])
            del waiting[i]
        for deps in waiting.values():
            deps.difference_update(ready)
    return ordered


def render_chain(specs: Sequence[Spec], *, directory: Path = GENERATED, smoke: bool = False) -> str:
    """The text of ``submit_all.sh``: submit each job, wait for it, check its output, go on.

    Args:
        specs: The specifications, in any order (``launch_order`` is applied).
        directory: Where the submit files and the script are; the script changes to the repository root itself.
        smoke: Chain the quick-run variants.

    Returns:
        The bash script.
    """
    try:
        to_root = os.path.relpath(REPOSITORY, Path(directory).resolve()).replace(os.sep, "/")
    except ValueError as error:  # another drive on Windows
        raise RenderError(f"{directory} is not on the drive of the repository") from error
    lines = [
        "#!/bin/bash",
        f"# {_BANNER}: submit the jobs one at a time, each after the previous one has finished.",
        "# A job that leaves no output stops the sequence. An earlier output is kept as <file>.previous.",
        "set -euo pipefail",
        f'cd "$(dirname "$0")/{to_root}"',
        "",
        "submit_and_wait() {  # name  submit-file  expected-output",
        '    if [[ -e "$3" ]]; then mv -f "$3" "$3.previous"; fi',
        "    local out cluster",
        '    out=$(condor_submit -terse "$2")',
        '    cluster="${out%%.*}"',
        '    echo "submitted $1 as cluster $cluster"',
        f'    condor_wait "{LOGS}/$1.$cluster.log"',
        '    if [[ ! -s "$3" ]]; then echo "FAILED: $1 left no $3 (see the logs of cluster $cluster)" >&2; exit 1; fi',
        '    echo "done $1 -> $3"',
        "}",
        "",
    ]
    for spec in launch_order(specs):
        args = [job_name(spec, smoke), _relative(sub_path(spec, directory, smoke)), expected_output(spec, smoke)]
        lines.append("submit_and_wait " + " ".join(shlex.quote(a) for a in args))
    return "\n".join(lines) + "\n"


def _resolve(items: Sequence[str]) -> List[Spec]:
    """Specifications given as YAML paths or as ``<series>/<name>`` identifiers."""
    known: Optional[Dict[str, Spec]] = None
    found = []
    for item in items:
        path = Path(item)
        if path.suffix == ".yaml" and path.exists():
            found.append(load_spec(path))
            continue
        known = known or {s.id: s for s in discover()}
        if item not in known:
            raise RenderError(f"{item}: not a YAML file and not one of {sorted(known)}")
        found.append(known[item])
    return found


def check(directory: Path = GENERATED) -> List[str]:
    """Problems of the generated files: a specification that does not render, a stale file, an orphan.

    Args:
        directory: Where the generated files are; a missing file is not a problem (they are not versioned).

    Returns:
        One message per problem (empty when everything is consistent).
    """
    problems: List[str] = []
    specs = discover()
    expected = {}
    for spec in specs:
        try:
            expected[sub_path(spec, directory).name] = render(spec)
            expected[sub_path(spec, directory, smoke=True).name] = render(spec, smoke=True)
        except RenderError as error:
            problems.append(str(error))
    for path in sorted(Path(directory).glob("*.sub")):
        if path.name not in expected:
            problems.append(f"{path.name}: no specification produces it (orphan)")
        elif path.read_text(encoding="utf-8") != expected[path.name]:
            problems.append(f"{path.name}: does not match its YAML (stale); render it again")
    return problems


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Command-line entry point.

    Args:
        argv: Arguments (``sys.argv[1:]`` when ``None``).

    Returns:
        0 on success, 1 if ``--check`` found a problem, 2 for a usage or specification error.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("specs", nargs="*", help="YAML files or <series>/<name> identifiers")
    parser.add_argument("--all", action="store_true", help="every specification under benchmarks/suites")
    parser.add_argument("--smoke", action="store_true", help="the quick-run variants")
    parser.add_argument("--chain", action="store_true", help="also write submit_all.sh (submit, wait, check, next)")
    parser.add_argument("--include-optional", action="store_true", help="include the optional ones in the chain")
    parser.add_argument("--check", action="store_true", help="do not write; fail on stale or orphan generated files")
    parser.add_argument("--output-dir", type=Path, default=GENERATED, help="where to write (default: generated/)")
    args = parser.parse_args(argv)
    try:
        if args.check:
            problems = check(args.output_dir)
            print("\n".join(problems) if problems else "generated submit files are consistent with the specifications")
            return 1 if problems else 0
        specs = discover() if args.all else _resolve(args.specs)
        if not specs:
            parser.error("give specifications or --all")
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for spec in specs:
            target = sub_path(spec, args.output_dir, args.smoke)
            target.write_text(render(spec, smoke=args.smoke), encoding="utf-8", newline="\n")
            print(f"wrote {target}")
        chained = [s for s in specs if args.include_optional or not s.optional]
        if args.chain:
            script = args.output_dir / "submit_all.sh"
            script.write_text(
                render_chain(chained, directory=args.output_dir, smoke=args.smoke), encoding="utf-8", newline="\n"
            )
            print(f"wrote {script}")
        print("submit in this order, each after the previous has finished:")
        for number, spec in enumerate(launch_order(chained), start=1):
            print(f"  {number}. {spec.id}  ->  {expected_output(spec, args.smoke)}")
        skipped = [s.id for s in specs if s not in chained]
        if skipped:
            print("optional, not in the chain: " + ", ".join(skipped))
    except (RenderError, SpecError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
