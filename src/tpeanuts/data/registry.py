"""The registry of downloadable datasets: what exists, where it comes from, and its checksums.

Large third-party data are not shipped with the package; each is described in the packaged file
``datasets.json`` by its license, citation and, for every file, URL, size and SHA-256. The checksum is
what makes a download trustworthy whatever the transport (one source is plain HTTP). The registry is
regenerated by ``tools/build_registry.py`` from the verified baseline manifest, never edited by hand.

Module contents:
    DatasetFile
        One downloadable file: relative path, URL, size and SHA-256.
    Dataset
        One dataset: name, description, license, citation and its files.
    load_registry(...)
        Read ``datasets.json`` into ``{name: Dataset}``.
    get_dataset(...)
        One dataset by name, with a helpful error for an unknown name.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Dict, Tuple

from tpeanuts.data import package_data


@dataclass(frozen=True)
class DatasetFile:
    """One file of a downloadable dataset.

    Attributes:
        path: Path relative to the dataset directory (also the name it is stored under).
        url: Where it is downloaded from (``https://``, ``http://`` or ``file://``).
        size: Expected size in bytes.
        sha256: Expected SHA-256, lowercase hex; every download is verified against it.
    """

    path: str
    url: str
    size: int
    sha256: str


@dataclass(frozen=True)
class Dataset:
    """A downloadable dataset.

    Attributes:
        name: Registry name, also the sub-directory under ``tpeanuts.data.datasets_dir()``.
        description: One-line description.
        license: License identifier or note (see ``DATA_LICENSES.md``).
        citation: What to cite when the data are used.
        homepage: Landing page of the data.
        files: Its files.
    """

    name: str
    description: str
    license: str
    citation: str
    homepage: str
    files: Tuple[DatasetFile, ...]

    @property
    def size(self) -> int:
        """Total size of all files, in bytes."""
        return sum(f.size for f in self.files)


def load_registry() -> Dict[str, Dataset]:
    """Read the packaged ``datasets.json``.

    Returns:
        ``{dataset name: Dataset}``.

    Raises:
        DataNotAvailableError: If the packaged registry is missing (broken installation).
        ValueError: If the registry has an unsupported schema version.
    """
    raw = json.loads(package_data("datasets.json").read_text(encoding="utf-8"))
    if raw.get("schema") != 1:
        raise ValueError(f"Unsupported datasets.json schema: {raw.get('schema')!r}.")
    registry: Dict[str, Dataset] = {}
    for name, entry in raw["datasets"].items():
        files = tuple(
            DatasetFile(path=f["path"], url=f["url"], size=int(f["size"]), sha256=f["sha256"].lower())
            for f in entry["files"]
        )
        registry[name] = Dataset(
            name=name, description=entry["description"], license=entry["license"],
            citation=entry["citation"], homepage=entry["homepage"], files=files,
        )
    return registry


def get_dataset(name: str) -> Dataset:
    """Return the dataset called ``name``.

    Args:
        name: Registry name, e.g. ``"icecube"``.

    Returns:
        The ``Dataset``.

    Raises:
        KeyError: If there is no such dataset; the message lists the known names.
    """
    registry = load_registry()
    if name not in registry:
        raise KeyError(f"Unknown dataset {name!r}. Available: {', '.join(sorted(registry))}.")
    return registry[name]
